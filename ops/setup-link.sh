#!/usr/bin/env bash
# Одноразовая ссылка для входа на страницу настройки переписки (обёртка над `shturman setup-link`).
#
# Страницу отдаёт сам сервис переписки, мимо Hermes: на ней владелец вводит ключи приложения
# Telegram, входит в свой аккаунт Telegram по QR-коду и выбирает чаты. Ассистент этой страницы
# не видит. Ссылка действует 30 минут и срабатывает один раз; новая ссылка отменяет прежнюю,
# а вход по новой ссылке завершает прежние входы на страницу.
#
#   ./ops/setup-link.sh           — ссылка на адрес страницы (SHTURMAN_SETUP_URL: по умолчанию то же
#                                   имя, что у ассистента, порт 8443); если адрес не задан или режим
#                                   без Hermes — на локальный адрес сервера, с подсказкой про туннель SSH
#   ./ops/setup-link.sh --local   — всегда на локальный адрес http://127.0.0.1:8765: страница
#                                   открывается через туннель SSH (прокси или порт ещё не готовы,
#                                   аварийный режим, режим без Hermes)
#   ./ops/setup-link.sh --help    — эта справка; ссылка при этом не выпускается
#
# У страницы свой адрес, отдельный от адреса дашборда: по адресу дашборда (SHTURMAN_PUBLIC_URL)
# она не отдаётся, и ссылка на него не выпускается никогда (почему — ./ops/set-setup-url.sh --help).
#
# Кто запускает. Лучше всего — сам владелец в своём терминале: тогда ссылку не видит никто, кроме
# него.
#
# ВАЖНО для агента: запускай только по явной просьбе владельца в текущей сессии — это стоп-точка.
# То, что печатает скрипт, — одноразовый пропуск: кто откроет ссылку, тот и настраивает сбор
# переписки владельца. Передай ссылку владельцу как есть и больше нигде её не сохраняй — ни
# в состоянии, ни в журнале, ни в отчёте; сам её не открывай и на страницу не заходи.
#
# Из .env читаются три несекретные строки: SHTURMAN_MODE, SHTURMAN_SETUP_URL и SHTURMAN_PUBLIC_URL
# (последняя — только чтобы сверить, что адреса разные). Остальное содержимое .env скрипт не читает
# и не печатает. Завершить все входы на страницу настройки (потеряно устройство): ./ops/logout-all.sh.
set -eu
cd "$(dirname "$0")/.." || exit 1
. ops/lib.sh
ops_help "$@"
local_only=no
for arg in "$@"; do
  case "$arg" in
    --local) local_only=yes ;;
    *) ops_unknown "$arg" ;;
  esac
done

svc=shturman-service
local_base="http://127.0.0.1:8765"
MODE="$(shturman_mode)" || exit 2
[ "$(container_state "$svc")" = "running" ] \
  || { echo "контейнер $svc не запущен — сначала ./ops/up.sh" >&2; exit 1; }

base="$local_base"
hint=""
if [ "$local_only" = no ] && [ "$MODE" = hermes ]; then
  url="$(url_origin "$(env_get SHTURMAN_SETUP_URL)")"
  if [ -n "$url" ]; then
    case "$url" in
      https://*) ;;
      *) echo "SHTURMAN_SETUP_URL в .env записан не как https://имя[:порт] — запишите заново: ./ops/set-setup-url.sh" >&2
         exit 1 ;;
    esac
    if [ "$url" = "$(url_origin "$(env_get SHTURMAN_PUBLIC_URL)")" ]; then
      echo "адрес страницы настройки совпадает с адресом дашборда — по общему адресу сервис её не отдаёт." >&2
      echo "Нужен другой адрес: ./ops/set-setup-url.sh (справка: --help)." >&2
      echo "До тех пор — ссылка на локальный адрес, через туннель SSH: ./ops/setup-link.sh --local" >&2
      exit 1
    fi
    # Сервис узнаёт свой внешний адрес при запуске (SHTURMAN_SETUP_ORIGIN). Адрес записали или
    # поменяли, а стек не перезапустили — страница по новому адресу вход не примет. Из окружения
    # контейнера берётся только эта несекретная строка.
    seen="$(docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' "$svc" 2>/dev/null \
      | sed -n 's/^SHTURMAN_SETUP_ORIGIN=//p' | tail -n 1)"
    if [ "$(url_origin "$seen")" != "$url" ]; then
      echo "сервис переписки запущен без адреса страницы настройки или с прежним — сначала ./ops/up.sh" >&2
      echo "(либо ссылка на локальный адрес, через туннель SSH: ./ops/setup-link.sh --local)" >&2
      exit 1
    fi
    base="$url"
  else
    hint=yes
  fi
fi

# Сервис печатает путь вида /shturman-setup/#<значение>. Значение стоит после «#»: при открытии
# ссылки браузер эту часть на сервер не отправляет. Путь идёт в стандартный вывод команды, её
# пояснения — в поток ошибок. Пояснения написаны для запуска без этой обёртки («допишите путь
# к адресу…») и называют адрес, с которым запущен сервис, а не тот, на который ссылку строит
# скрипт (с --local это разные адреса). Поэтому при успехе они не показываются — то же самое
# сказано ниже своими словами; при неудаче показываются как есть: значения ссылки в них нет.
errf="$(mktemp)"
if ! out="$(docker exec "$svc" shturman setup-link 2>"$errf")"; then
  cat "$errf" >&2
  rm -f "$errf"
  echo "сервис не выдал ссылку. Если у него нет такой команды — сервис прежней версии: страница" >&2
  echo "настройки переписки появилась в 0.0.6, обновите экземпляр (UPGRADING.md)." >&2
  exit 1
fi
rm -f "$errf"
path="$(printf '%s\n' "$out" | grep -m 1 -E '^/shturman-setup/#[A-Za-z0-9_-]{16,256}$' || true)"
out=""
if [ -z "$path" ]; then
  # Сам ответ не печатаем: в нём может быть значение ссылки в непривычном виде.
  echo "сервис ответил не ссылкой вида /shturman-setup/#… — ссылка не выдана" >&2
  exit 1
fi

printf '%s%s\n' "$base" "$path"
path=""
echo "Одноразовая ссылка входа на страницу настройки переписки. Действует 30 минут и срабатывает один раз;" >&2
echo "новая ссылка отменяет эту, а вход по ссылке завершает прежние входы на страницу." >&2
echo "Кто откроет ссылку, тот и войдёт: передайте её владельцу как есть и нигде не сохраняйте." >&2
if [ "$base" = "$local_base" ]; then
  echo "Адрес локальный: страница открывается только с самого сервера. Со своего компьютера —" >&2
  echo "через туннель SSH (тот же, что в ./ops/connect.sh, шаг 2; порт слева обязан быть 8765):" >&2
  echo "  ssh -N -L 8765:127.0.0.1:8765 <сервер>" >&2
  echo "Пока туннель открыт, ссылка работает в браузере на вашем компьютере." >&2
fi
if [ -n "$hint" ]; then
  echo "У страницы нет внешнего адреса. Чтобы открывать её без туннеля: ./ops/set-setup-url.sh --help" >&2
fi
