#!/usr/bin/env bash
# Одноразовая ссылка для входа на страницу настройки переписки (обёртка над `shturman setup-link`).
#
# Страницу отдаёт сам сервис переписки, мимо Hermes: на ней владелец вводит токен бота
# согласований и ключи приложения Telegram, входит в аккаунт Telegram по QR-коду, выбирает чаты
# и загружает выгрузку. Ассистент этой страницы не видит. Ссылка действует 30 минут и срабатывает
# один раз; новая ссылка отменяет прежнюю. Дальше владелец входит по коду от бота согласований.
#
#   ./ops/setup-link.sh           — ссылка на внешний адрес экземпляра (режим с Hermes и заданный
#                                   SHTURMAN_PUBLIC_URL); иначе — на локальный адрес сервера
#   ./ops/setup-link.sh --local   — всегда на локальный адрес http://127.0.0.1:8765: страница
#                                   открывается через туннель SSH (прокси ещё не настроен,
#                                   аварийный режим, режим без Hermes)
#   ./ops/setup-link.sh --help    — эта справка; ссылка при этом не выпускается
#
# Кто запускает. Лучше всего — сам владелец в своём терминале: тогда ссылку не видит никто, кроме
# него.
#
# ВАЖНО для агента: запускай только по явной просьбе владельца в текущей сессии — это стоп-точка.
# То, что печатает скрипт, — одноразовый пропуск: кто откроет ссылку, тот и настраивает сбор
# переписки владельца. Передай ссылку владельцу как есть и больше нигде её не сохраняй — ни
# в состоянии, ни в журнале, ни в отчёте; сам её не открывай.
#
# Из .env читаются две несекретные строки: SHTURMAN_MODE и SHTURMAN_PUBLIC_URL. Остальное
# содержимое .env скрипт не читает и не печатает. Завершить все входы на страницу настройки
# (потеряно устройство): ./ops/logout-all.sh.
set -eu
cd "$(dirname "$0")/.." || exit 1
. ops/lib.sh
ops_help "$@"
local_only=no
for arg in "$@"; do
  case "$arg" in
    --local) local_only=yes ;;
    *) ops_unknown "$arg" ;;
  esac
done

svc=shturman-service
local_base="http://127.0.0.1:8765"
MODE="$(shturman_mode)" || exit 2
[ "$(container_state "$svc")" = "running" ] \
  || { echo "контейнер $svc не запущен — сначала ./ops/up.sh" >&2; exit 1; }

base="$local_base"
if [ "$local_only" = no ] && [ "$MODE" = hermes ]; then
  url="$(env_get SHTURMAN_PUBLIC_URL)"
  if [ -n "$url" ]; then
    # Сервис узнаёт внешний адрес при запуске (SHTURMAN_SETUP_ORIGIN). Адрес поменяли, а стек
    # не перезапустили — страница по новому адресу вход не примет. Из окружения контейнера
    # берётся только эта несекретная строка.
    seen="$(docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' "$svc" 2>/dev/null \
      | sed -n 's/^SHTURMAN_SETUP_ORIGIN=//p' | tail -n 1)"
    if [ "$seen" != "$url" ]; then
      echo "сервис переписки запущен без внешнего адреса или с прежним — сначала ./ops/up.sh" >&2
      echo "(либо ссылка на локальный адрес, через туннель SSH: ./ops/setup-link.sh --local)" >&2
      exit 1
    fi
    base="${url%/}"
  fi
fi

# Сервис печатает путь вида /shturman-setup/#<значение>. Значение стоит после «#»: при открытии
# ссылки браузер эту часть на сервер не отправляет.
if ! out="$(docker exec "$svc" shturman setup-link)"; then
  echo "сервис не выдал ссылку. Если у него нет такой команды — сервис прежней версии: страница" >&2
  echo "настройки переписки появилась в 0.0.6, обновите экземпляр (UPGRADING.md)." >&2
  exit 1
fi
path="$(printf '%s\n' "$out" | grep -m 1 -E '^/shturman-setup/#[A-Za-z0-9_-]{16,256}$' || true)"
out=""
if [ -z "$path" ]; then
  # Сам ответ не печатаем: в нём может быть значение ссылки в непривычном виде.
  echo "сервис ответил не ссылкой вида /shturman-setup/#… — ссылка не выдана" >&2
  exit 1
fi

printf '%s%s\n' "$base" "$path"
path=""
echo "Действует 30 минут и срабатывает один раз; новая ссылка отменяет эту." >&2
if [ "$base" = "$local_base" ]; then
  echo "Адрес локальный: страница открывается только с самого сервера. Со своего компьютера —" >&2
  echo "через туннель SSH (тот же, что в ./ops/connect.sh, шаг 2; порт слева обязан быть 8765):" >&2
  echo "  ssh -N -L 8765:127.0.0.1:8765 <сервер>" >&2
  echo "Пока туннель открыт, ссылка работает в браузере на вашем компьютере." >&2
fi
