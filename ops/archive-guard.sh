#!/usr/bin/env bash
# Граница выдачи архива ассистенту (Р-104, docs/service.md, «Граница выдачи архива»).
#   ./ops/archive-guard.sh status — состояние (открыта, приторможена, закрыта), пределы, сколько выдано за час
#                                   и сутки по видам токена, ловушки и тревоги. Только числа: ни текста переписки,
#                                   ни названий чатов.
#   ./ops/archive-guard.sh close  — закрыть ассистенту доступ к архиву сразу (ужесточение; владельцу — сообщение
#                                   в бот согласований).
#   ./ops/archive-guard.sh open   — снова открыть выдачу после тревоги или закрытия. Это ОСЛАБЛЕНИЕ: только по явной
#                                   просьбе владельца в текущей сессии, и лучше — кнопкой «Это я, продолжить» или
#                                   «Вернуть доступ» в самом боте согласований. Запасной путь, когда своего бота
#                                   у сервиса нет. Владелец получает сообщение об открытии.
# Пределы (SHTURMAN_ARCHIVE_* в .env) этот скрипт не меняет: ослабляет их только владелец.
# -h, --help — эта справка.
set -eu
cd "$(dirname "$0")/.." || exit 1
. ops/lib.sh
ops_help "$@"

action="${1:-}"
case "$action" in
  status|open|close) shift ;;
  *) ops_unknown "${action:-без действия}" ;;
esac
[ "$#" -eq 0 ] || ops_unknown "$1"

svc=shturman-service
if [ "$(container_state "$svc")" != "running" ]; then
  echo "контейнер $svc не запущен — ./ops/up.sh и повторите" >&2
  exit 1
fi
docker exec "$svc" shturman archive-guard "$action"
