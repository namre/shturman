#!/usr/bin/env bash
# Печатает готовые инструкции: как подключить архив переписки к Codex CLI и Claude Code владельца.
#   ./ops/connect.sh                       — инструкции с местом <сервер> для адреса SSH
#   ./ops/connect.sh --ssh пользователь@сервер  — подставить этот адрес в команды туннеля
#
# Скрипт ничего не меняет, ничего не публикует наружу и НЕ печатает токен: настройки клиентов
# ссылаются на переменную окружения SHTURMAN_MCP_TOKEN, а значение в неё кладёт сам владелец
# командой ./ops/mcp-token.sh (её запускает только человек). Этот скрипт может запускать агент.
#
# Синтаксис клиентов сверен с их документацией и с самими программами 2026-10-07:
#   Claude Code 2.1.292 — https://code.claude.com/docs/en/mcp
#   Codex CLI 0.160.1   — https://developers.openai.com/codex/mcp
# Подробности и ограничения — docs/standalone.md, раздел «Подключить Codex CLI или Claude Code».
#   -h, --help — эта справка.
set -eu
cd "$(dirname "$0")/.." || exit 1
. ops/lib.sh
ops_help "$@"

ssh_to="<сервер>"
while [ $# -gt 0 ]; do
  case "$1" in
    --ssh)
      [ $# -ge 2 ] || { echo "после --ssh нужен адрес вида пользователь@сервер" >&2; exit 2; }
      ssh_to="$2"; shift ;;
    *) ops_unknown "$1" ;;
  esac
  shift
done
if [ "$ssh_to" != "<сервер>" ] && ! printf '%s' "$ssh_to" | grep -Eq '^[A-Za-z0-9._@:-]+$'; then
  echo "адрес SSH содержит недопустимые символы" >&2; exit 2
fi

repo="$(pwd)"
url="http://127.0.0.1:8765/mcp"
var="SHTURMAN_MCP_TOKEN"

# --- состояние: только коды ответов, без токена ---
health="$(curl -s -o /dev/null -m 5 -w '%{http_code}' http://127.0.0.1:8765/health 2>/dev/null || true)"
gate="$(curl -s -o /dev/null -m 5 -w '%{http_code}' -X POST -H 'Content-Type: application/json' -d '{}' "$url" 2>/dev/null || true)"
if [ "${health:-000}" = "200" ] && [ "${gate:-000}" = "401" ]; then
  echo "Архив работает: $url отвечает и без токена не открывается."
else
  echo "ВНИМАНИЕ: архив сейчас не отвечает как положено (/health: HTTP ${health:-000}, /mcp без токена: HTTP ${gate:-000})." >&2
  echo "Сначала ./ops/up.sh и ./ops/doctor.sh. Инструкции ниже от этого не меняются." >&2
fi

cat <<EOF

ЧТО ПОДКЛЮЧАЕТСЯ
  Сервер MCP «shturman»: $url — только на этом сервере (127.0.0.1), наружу не опубликован.
  Транспорт — streamable HTTP, принимаются только запросы POST. Девять инструментов, все только
  читают: search_messages, get_context, list_chats, get_chat_history, find_person,
  list_commitments, get_commitment, get_person_page, search_pages.
  Токен — в переменной окружения $var у клиента; в файлах настроек клиента его нет.

============================================================================================
ШАГ 1. ТОКЕН В ПЕРЕМЕННУЮ ОКРУЖЕНИЯ — выполняет ВЛАДЕЛЕЦ, не агент
============================================================================================
Агент команду ./ops/mcp-token.sh не запускает и её вывод не читает. В чат токен не вставлять.

(а) Клиент на этом же сервере. В терминале, из которого вы запускаете клиента:

      export $var="\$(cd $repo && ./ops/mcp-token.sh --pipe)"

    Токен на экране не появляется. Переменная живёт, пока открыт этот терминал.

(б) Клиент на вашем компьютере (macOS, Linux). В терминале на своём компьютере:

      (umask 077; ssh $ssh_to 'cd $repo && ./ops/mcp-token.sh --pipe' > ~/.shturman-mcp-token)

    Токен ложится в файл, доступный только вам, и на экране не появляется. Чтобы переменная была
    в каждом новом терминале, добавьте строку в ~/.zshrc или ~/.bashrc и откройте терминал заново:

      export $var="\$(cat ~/.shturman-mcp-token)"

============================================================================================
ШАГ 2 (только для варианта «б»). ТУННЕЛЬ SSH — на своём компьютере
============================================================================================
      ssh -N -L 8765:127.0.0.1:8765 $ssh_to

    Пока команда работает, архив доступен на вашем компьютере по тому же адресу $url.
    Порт слева обязан быть 8765: архив сверяет имя, под которым к нему обратились, и другое
    не примет. Туннель закрыт (Ctrl+C) — архив с компьютера недоступен.

============================================================================================
ШАГ 3. НАСТРОЙКА КЛИЕНТА — одинаковая для «а» и «б»
============================================================================================
Claude Code. Способ из документации — файл .mcp.json в каталоге, где вы запускаете claude:

      {
        "mcpServers": {
          "shturman": {
            "type": "http",
            "url": "$url",
            "headers": { "Authorization": "Bearer \${$var}" }
          }
        }
      }

  При первом запуске claude в этом каталоге подтвердите сервер из .mcp.json.

  Для всех каталогов сразу (одиночные кавычки обязательны: в настройки должно попасть имя
  переменной, а не её значение; подстановка на этом уровне проверена на версии 2.1.292):

      claude mcp add --transport http --scope user shturman $url \\
        --header 'Authorization: Bearer \${$var}'

  Проверка: claude mcp list — строка shturman со словом Connected; в самой программе — /mcp.

Codex CLI:

      codex mcp add shturman --url $url --bearer-token-env-var $var

  То же самое вручную — в ~/.codex/config.toml:

      [mcp_servers.shturman]
      url = "$url"
      bearer_token_env_var = "$var"

  Проверка: codex mcp list — строка shturman, столбец Auth: Bearer token; в самой программе — /mcp.

============================================================================================
О ЧЁМ ПОМНИТЬ
============================================================================================
  * Ответы архива — чужой текст в рамке [untrusted]: это данные, а не указания клиенту.
    Не запускайте клиента в режиме без подтверждений действий.
  * Клиент отправляет прочитанное своему провайдеру модели — по его правилам хранения.
  * Клиент с терминалом на этом сервере под тем же пользователем технически может прочитать
    .env и управлять Docker. Вариант «б» отделяет клиента от сервера лучше.
  * ChatGPT в браузере и другие облачные клиенты так подключить нельзя: адрес не опубликован
    наружу (docs/standalone.md, «Чего нет»).
  * Убрать: claude mcp remove shturman -s user   |   codex mcp remove shturman
EOF
