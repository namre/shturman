#!/usr/bin/env bash
# Одноразовая ссылка привязки владельца к боту согласований (обёртка над `shturman bot-bind`).
#
# Тот, кто откроет ссылку в Telegram и нажмёт «Запустить», становится владельцем: ему бот
# присылает карточки, и только его нажатия кнопок считаются решениями. Ссылка действует
# 15 минут и срабатывает один раз; новая ссылка отменяет прежнюю. В базе лежит только её хеш.
#
# Кто запускает. Лучше всего — сам владелец в своём терминале: тогда ссылку не видит никто,
# кроме него (без Hermes он и так только что вводил здесь токен бота: ./ops/init-env.sh).
#
# ВАЖНО для агента: запускай только по явной просьбе владельца в текущей сессии — это
# стоп-точка. То, что печатает скрипт, — одноразовый пропуск во владельцы, как ссылка активации:
# передай ссылку владельцу как есть и больше нигде её не сохраняй — ни в состоянии, ни в журнале,
# ни в отчёте; сам её не открывай. Если владелец уже привязан, сначала скажи ему: откроет ссылку
# другой аккаунт — владелец сменится, ждущие черновики отклонятся, список доверенных очистится.
set -eu
cd "$(dirname "$0")/.." || exit 1
. ops/lib.sh

svc=shturman-service
[ "$(container_state "$svc")" = "running" ] \
  || { echo "контейнер $svc не запущен — сначала ./ops/up.sh" >&2; exit 1; }

# Если токен бота не задан или бот ещё не связался с Telegram, команда сама скажет об этом
# и завершится с ошибкой: состояние бота — `docker exec shturman-service shturman bot-status`.
exec docker exec "$svc" shturman bot-bind
