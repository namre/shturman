#!/usr/bin/env bash
# Выдаёт владельцу токен архива (SHTURMAN_MCP_TOKEN, только чтение), чтобы он положил его
# в переменную окружения своего Codex CLI или Claude Code. Что делать с ним дальше — ./ops/connect.sh.
#
# ВЫВОДИТ СЕКРЕТ — ЗАПУСКАЕТ ТОЛЬКО ЧЕЛОВЕК в своём терминале. Агент этот скрипт не запускает, его вывод
# не читает и не просит показать: токен открывает всю переписку владельца на чтение (AGENTS.md).
# Скрипт сам проверяет, что его запустил человек: ввод — с настоящего терминала (stdin — терминал
# и у процесса есть управляющий терминал /dev/tty). Команда, которую агент выполняет с перехватом
# вывода (Codex, Claude Code), терминала не имеет — скрипт отказывает с кодом 2, ничего не печатая из .env.
# Предел: программа, которая сама изображает терминал (псевдотерминал), эту проверку проходит; от
# агента, решившего обойти правила, защищает не скрипт, а права на сервере (docs/security-review.md, «Противники»).
#
#   ./ops/mcp-token.sh --pipe        — напечатать только токен, когда вывод идёт НЕ на экран, — для
#                                      подстановки в своём терминале на этом сервере:
#       export SHTURMAN_MCP_TOKEN="$(./ops/mcp-token.sh --pipe)"
#   ./ops/mcp-token.sh --out ФАЙЛ    — записать токен в ФАЙЛ с правами 600 (только вам) и напечатать
#                                      только путь. Для клиента на своём компьютере (./ops/connect.sh):
#       ssh -t <сервер> 'cd <каталог> && ./ops/mcp-token.sh --out ~/.shturman-mcp-token'
#       scp <сервер>:.shturman-mcp-token ~/.shturman-mcp-token && chmod 600 ~/.shturman-mcp-token
#       ssh <сервер> 'rm -f ~/.shturman-mcp-token'
#                                      ФАЙЛ — вне каталога репозитория; существующий файл перезаписывается,
#                                      ссылка (symlink) — нет.
#   ./ops/mcp-token.sh               — показать токен на экране один раз, после подтверждения.
#                                      Запасной путь: то, что было на экране, остаётся в прокрутке
#                                      терминала и в буфере обмена.
#
# Из .env читается одна строка — SHTURMAN_MCP_TOKEN, и только после проверки терминала.
# Сменить токен (если он мог попасть к постороннему): удалить строку SHTURMAN_MCP_TOKEN из .env,
# затем ./ops/init-env.sh --auto и ./ops/up.sh — прежний токен перестанет действовать.
#
#   -h, --help — эта справка; токен при этом не читается и не печатается.
set -eu
cd "$(dirname "$0")/.." || exit 1
. ops/lib.sh
ops_help "$@"

mode=show; out=""
case "${1:-}" in
  "") ;;
  --pipe) mode=pipe; [ $# -le 1 ] || ops_unknown "$2" ;;
  --out)
    mode=out
    [ $# -ge 2 ] && [ -n "$2" ] || { echo "после --out нужен путь к файлу" >&2; exit 2; }
    out="$2"
    [ $# -le 2 ] || ops_unknown "$3" ;;
  *) ops_unknown "$1" ;;
esac

# Запустил ли человек: ввод с терминала и есть управляющий терминал. Без этого — отказ до чтения .env.
human_terminal() {
  [ -t 0 ] || return 1
  (: < /dev/tty) 2> /dev/null || return 1
  return 0
}
if ! human_terminal; then
  echo "Токен архива выдаётся только человеку в его собственном терминале: у этого запуска терминала нет" >&2
  echo "(так запускает команды ИИ-агент — его вывод уходит провайдеру модели). Агенту этот скрипт запускать нельзя." >&2
  echo "Владелец: откройте терминал сам и выполните команду из ./ops/connect.sh." >&2
  exit 2
fi
if [ "$mode" = pipe ] && [ -t 1 ]; then
  echo "С ключом --pipe токен на экран не выводится. Используйте подстановку:" >&2
  echo "  export SHTURMAN_MCP_TOKEN=\"\$(./ops/mcp-token.sh --pipe)\"" >&2
  exit 2
fi
if [ "$mode" = show ] && [ ! -t 1 ]; then
  echo "Без ключа токен показывается только на экране. Для подстановки — --pipe, для файла — --out ФАЙЛ." >&2
  exit 2
fi
if [ "$mode" = out ]; then
  case "$out" in \~/*) out="$HOME/${out#\~/}" ;; esac
  dir="$(dirname "$out")"
  [ -d "$dir" ] || { echo "нет каталога: $dir" >&2; exit 2; }
  absdir="$(cd "$dir" && pwd -P)"; repo="$(pwd -P)"
  case "$absdir/" in "$repo"/*) echo "файл токена не кладётся в каталог репозитория ($repo): его подхватят копии и git" >&2; exit 2 ;; esac
  [ ! -L "$out" ] || { echo "$out — ссылка (symlink): токен по ней не записывается" >&2; exit 2; }
  [ ! -e "$out" ] || [ -f "$out" ] || { echo "$out — не обычный файл" >&2; exit 2; }
  out="$absdir/$(basename "$out")"
fi

[ -f .env ] || { echo "нет .env — сначала ./ops/init-env.sh --auto" >&2; exit 1; }
token="$(grep -E '^SHTURMAN_MCP_TOKEN=' .env | tail -n 1 | cut -d= -f2- || true)"
[ -n "$token" ] || { echo "токен архива не задан — запустите ./ops/init-env.sh --auto" >&2; exit 1; }

case "$mode" in
  pipe)
    printf '%s\n' "$token"
    exit 0 ;;
  out)
    tmp="$(umask 077; mktemp "$absdir/.shturman-mcp-token.XXXXXX")"
    printf '%s\n' "$token" > "$tmp"
    chmod 600 "$tmp"
    mv -f "$tmp" "$out"
    echo "Токен архива записан в $out (права 600, на экран не выводился)."
    echo "Дальше — шаги из ./ops/connect.sh. В чат с ИИ-агентом токен и содержимое файла не вставляйте."
    exit 0 ;;
esac

echo "Токен архива появится на экране. Он даёт чтение всей вашей переписки в архиве."
echo "Убедитесь, что экран никто не видит и не записывает; после этого очистите терминал."
printf 'Чтобы показать, напишите «да»: '
IFS= read -r answer
[ "$answer" = "да" ] || { echo "отменено"; exit 1; }
printf '\n%s\n\n' "$token"
echo "Положите его в переменную окружения SHTURMAN_MCP_TOKEN на своём компьютере (./ops/connect.sh)."
echo "В чат с ИИ-агентом токен не вставляйте."
