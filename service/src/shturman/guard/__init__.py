"""Защита от внедрённых инструкций (prompt injection) в чужих сообщениях.

Три места проверки:
  1. на входе  — каждое входящее сообщение получает оценку малой модели-классификатора;
                 пока оценки нет или она плохая, сообщение ассистенту и модели не показывается;
  2. перед обработкой — в промпты (обязательства, сводки, автоответ, наблюдатель) попадают
                 только видимые сообщения;
  3. на выходе — черновики и автоответы проверяются перед отправкой.

Договорённость с остальными модулями — один столбец: `messages.agent_visible`. Всё, что отдаёт
текст переписки ассистенту или модели, добавляет условие `AND m.agent_visible`. Как именно
столбец получает значение — дело этого пакета.

Состояние сообщения хранит `messages.guard_label`:
  NULL        — ещё не проверено;
  ok          — чисто;
  suspect     — сомнительно (показывается с пометкой либо скрывается — настройка владельца);
  blocked     — похоже на внедрённую инструкцию, скрыто;
  released    — владелец сказал «обычное сообщение», видно, повторно не проверяется;
  confirmed   — владелец оставил скрытым.
"""

from __future__ import annotations

from typing import Protocol, Sequence

LEVELS = ("soft", "normal", "strict")
LABELS = ("ok", "suspect", "blocked", "released", "confirmed")


class Scorer(Protocol):
    """Модель-классификатор. Работает на сервере, в сеть не ходит."""

    name: str   # имя и версия модели: пишется в messages.guard_model

    def score(self, texts: Sequence[str]) -> list[float]:
        """Вероятность (0…1) того, что текст — попытка управлять ассистентом. Вызывается в
        отдельном потоке: внутри можно считать на процессоре."""
