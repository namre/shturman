"""Защита от внедрённых инструкций (prompt injection) в чужих сообщениях. Одна точка проверки.

Что делает. Каждое входящее (не от владельца) текстовое сообщение при записи в архив получает
оценку классификатора. Оценка не ниже порога — сообщение скрывается от ассистента
(`messages.agent_visible = false`, `guard_label = 'suspect'`), а владелец получает одно
уведомление с двумя кнопками: «Показать ассистенту» и «Оставить скрытым».

Чего не делает. Это снижение риска, а не устранение: классификатор пропускает часть атак
и иногда скрывает обычные сообщения. Измеренные числа и границы применимости — `docs/guard.md`.
Промпты и исходящие черновики этот пакет не проверяет: проверка одна, на входе.

Договорённость с остальными модулями — один столбец: `messages.agent_visible`. Всё, что отдаёт
текст переписки ассистенту или модели, добавляет условие `AND m.agent_visible`. Как именно
столбец получает значение — дело этого пакета.

Состояние сообщения хранит `messages.guard_label` (миграция 0014_guard.sql):
  NULL        — не проверено (защита выключена, модель недоступна, очередь не дошла);
  ok          — проверено, обычное сообщение;
  suspect     — похоже на внедрённую инструкцию: скрыто, ждёт решения владельца;
  released    — владелец сказал «обычное сообщение»: видно, повторно не проверяется;
  confirmed   — владелец оставил скрытым.

Когда сообщение видно до оценки:
  * живой поток (сессия аккаунта, бизнес-бот) — нет: при включённой защите сообщение пишется
    скрытым (`store.upsert_messages(hold=True)`) и сразу проверяется (`screen`); остальные модули
    узнают о нём уже после проверки. Модель недоступна — сообщение открывается непроверенным;
  * импорт выгрузки и догрузка истории — да: сообщения видны сразу, фоновая работа проверяет их
    пачками, начиная с самых свежих. Сотни тысяч сообщений проверяются часами, и прятать на это
    время весь архив — значит оставить ассистента без памяти.

Части пакета: `rules` — правила без модели; `tei` — клиент контейнера с моделью; `core` —
проверка и запись итога; `alerts` — уведомления владельцу и его решения; `service` — запуск
в составе сервиса, маршруты `/api/guard/*`.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol, Sequence

if TYPE_CHECKING:
    from .core import Guard

LABELS = ("ok", "suspect", "released", "confirmed")


class Scorer(Protocol):
    """Модель-классификатор. Работает на сервере, в сеть не ходит."""

    name: str   # имя и версия модели: пишется в messages.guard_model

    def score(self, texts: Sequence[str]) -> list[float]:
        """Вероятность (0…1) того, что текст — попытка управлять ассистентом. Вызывается в
        отдельном потоке: внутри можно считать на процессоре или ждать ответа по сети."""


# Работающая защита процесса сервиса. Её ставит `service.lifespan`; None — защита выключена.
_current: "Guard | None" = None


def current() -> "Guard | None":
    return _current


def set_current(guard: "Guard | None") -> None:
    global _current
    _current = guard


def holding() -> bool:
    """Писать ли новые входящие из живых источников скрытыми до проверки."""
    return _current is not None


async def screen(message_ids: Sequence[int]) -> set[int]:
    """Проверяет только что записанные сообщения живого источника. Возвращает идентификаторы
    тех, что остались скрытыми: о них остальным модулям не сообщают. Защита выключена — пусто."""
    guard = _current
    if guard is None or not message_ids:
        return set()
    return await guard.screen(message_ids)
