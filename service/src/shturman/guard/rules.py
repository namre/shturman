# Слабый признак не считается, если сработал сильный того же рода: «игнорируй все предыдущие
# инструкции» — одна просьба, а не две.
_SUPERSEDED = {"override_soft": "override", "secrecy_people": "secrecy", "tool_generic": "tool"}
# Признак, который считается только вместе с одним из названных.
_NEEDS = {"target": ("exfil",)}

THRESHOLD = 0.5
# Признаки, которые поодиночке почти не встречаются в речи между людьми и сами по себе решают
# (вес не ниже 0,8): отмена прежних инструкций, раскрытие системных инструкций, «инструкции
# больше не действуют». Массовое решение «Показать всё, кроме сработавших по правилам с высоким
# весом» (alerts.py) оставляет такие сообщения скрытыми для разбора по одному.
HIGH_WEIGHT = 0.8

_QUOTED = re.compile(r"«[^«»]{0,400}»|\"[^\"]{0,400}\"|“[^“”]{0,400}”|„[^„“”]{0,400}[“”]")


def _all_quoted(rule: Rule, value: str, spans: list[tuple[int, int]]) -> bool:
    found = list(rule.pattern.finditer(value))
    return bool(found) and all(any(a <= m.start() and m.end() <= b for a, b in spans) for m in found)


def explain(text: str) -> list[Rule]:
    """Сработавшие признаки — для объяснения владельцу и для оценки. Признак, у которого каждое
    совпадение стоит в кавычках, возвращается с весом `quoted` и кодом `<код>_quoted`."""
    value = normalize(text)
    spans = [(m.start(), m.end()) for m in _QUOTED.finditer(value)]
    fired: list[Rule] = []
    for rule in RULES:
        if not rule.pattern.search(value):
            continue
        if rule.quoted is not None and spans and _all_quoted(rule, value, spans):
            rule = replace(rule, code=rule.code + "_quoted", weight=rule.quoted,
                           reason=rule.reason + " (в кавычках — похоже на разговор об этом)")
        fired.append(rule)
    families = {rule.code.removesuffix("_quoted") for rule in fired}
    return [rule for rule in fired
            if _SUPERSEDED.get(rule.code.removesuffix("_quoted")) not in families
            and all(need in families for need in _NEEDS.get(rule.code, ()))]


def score_one(text: str) -> float:
    miss = 1.0
    for rule in explain(text):
        miss *= 1.0 - rule.weight
    return round(1.0 - miss, 4)


def high_weight(text: str) -> bool:
    """Сработал ли признак с весом не ниже `HIGH_WEIGHT` (не в кавычках)."""
    return any(rule.weight >= HIGH_WEIGHT for rule in explain(text))


class RulesScorer:
    """`Scorer` на правилах. Модели не нужна, в сеть не ходит."""

    name = NAME
    threshold = THRESHOLD

    def score(self, texts: Sequence[str]) -> list[float]:
        return [score_one(text) for text in texts]
