"""Страница настройки сервиса: /shturman-setup/.

Единственное, что сервис отдаёт человеку, а не плагину и не агенту. Свой вход (одноразовая ссылка
из `./ops/setup-link.sh`; код от бота согласований — только когда бот настроен), своя сессия,
свои маршруты. С внутренним API (`/api/*`) и архивом для агента (`/mcp`) страница не пересекается:
их токены здесь входом не служат, а их маршруты отсюда недоступны.

Страница живёт на своём origin — на другом порту того же имени, что и дашборд Hermes, либо на
другом имени: скрипт с адреса дашборда не достаёт ни до её хранилища, ни до её запросов
(`shield.py`). Сессия — без cookie: ключ в `localStorage` страницы и в заголовке запроса (`auth.py`).

Первый шаг — бот согласований (токен и привязка владельца): без него остальные шаги закрыты.
Второй — выбор способа подключения, хранится в setup_state: own — «ассистент видит всё как вы»
(ключи приложения Telegram, вход в основной аккаунт на чтение, выбор чатов); staff — «ассистент —
отдельный сотрудник» (бизнес-режим у бота согласований, по желанию для групп — ключи приложения,
аккаунт ассистента, выбор его групп). Выгрузка из Telegram Desktop — по желанию в обоих. Шаг
другого способа, где уже что-то подключено, виден без номера. Под шагами — «Повседневное»: сферы,
уведомления, наблюдатель, репетиция, память, журнал действий; в блоке «Дополнительно» — своя модель и
«Что собрано». Когда обязательные шаги пройдены, страница — пульт: готовые шаги свёрнуты в строку,
сверху быстрые ссылки и карточка «Сейчас» (пакет 3 ревизии удобства).

Состав:
  secrets_store.py — файл значений, введённых на странице, и их слияние с окружением;
  auth.py          — ссылки входа, коды от бота, сессии;
  shield.py        — проверка имени узла и строгие заголовки для всего префикса;
  audit.py         — журнал действий владельца;
  apply.py         — проверка введённых значений и применение их без перезапуска сервиса
                     (адрес модели — только https и только наружу: `shturman/netguard.py`);
  summary.py       — признаки для `GET /api/status` (объект `setup`);
  service.py       — маршруты и запуск;
  memory.py        — экран «Память ассистента»: страницы о людях, заметки владельца, «ждут решения»;
  initdata.py      — проверка данных входа Mini App (подпись Telegram для бота согласований);
  miniapp.py       — Mini App бота согласований: вход по данным Telegram, своя узкая сессия, маршруты;
  approvals.py     — экран «Согласования» приложения: те же кнопки, что в боте, тем же путём;
  chats.py         — какие чаты читать: общее для страницы и экрана «Чаты» приложения (Р-80);
  static/          — сама страница и приложение: HTML, CSS и JS без сборки и без внешних запросов.

Mini App живёт под тем же префиксом и на том же адресе, что страница (`/shturman-setup/app/`), —
не на адресе дашборда: обратный прокси менять не нужно, а скрипт с адреса дашборда до
приложения не дотягивается. Рамку (iframe) разрешено открыть только web.telegram.org и только для
самого приложения; остальная страница в рамке не открывается (`shield.py`).
"""

