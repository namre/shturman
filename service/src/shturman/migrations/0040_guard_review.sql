-- Защита на настоящей переписке: история без поштучных карточек и массовое решение владельца
-- (Р-99, docs/guard.md, «Скрытое из истории и решение разом»).

-- Нужна ли скрытому сообщению отдельная карточка владельцу. true — живой поток (проверено сразу при
-- записи) или свежее (последняя правка или отправка не раньше чем за 24 часа до проверки); false —
-- история: импорт выгрузки, догрузка старых сообщений. История решается сводкой с кнопками «разом»,
-- поштучно — только по просьбе владельца («Разбирать по одной»). NULL — сообщение проверено до этой
-- миграции: тогда то же правило считается по времени отправки и проверки (guard/alerts.py).
ALTER TABLE messages ADD COLUMN guard_card boolean;

-- Как владелец решил: card — кнопкой под карточкой сообщения (в боте или в приложении); bulk —
-- разом, сводкой («Показать ассистенту все скрытые», «… кроме сильных правил», «Оставить все
-- скрытыми»). Решение сводкой записывается так же, как поштучное, — на каждый текст, и так же
-- запоминается; доля «показать» среди решённых поштучно — оценка ложных срабатываний
-- (`./ops/guard.sh stats`), решённое разом считается отдельно: владелец не смотрел каждое.
-- Предел карточек в час считает только via = 'card'.
ALTER TABLE guard_alerts ADD COLUMN via text NOT NULL DEFAULT 'card' CHECK (via IN ('card', 'bulk'));
