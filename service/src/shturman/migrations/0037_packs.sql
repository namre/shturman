-- Пачка сообщений — одно высказывание (решение Р-93, service/src/shturman/packs.py).
--
-- Сообщения одного отправителя подряд с паузами не больше PACK_GAP и все сообщения одного альбома
-- Telegram — одна пачка: одно уведомление, один разбор входящих, одна карточка репетиции, один ответ.
--
-- grouped_id — номер альбома Telegram: у фото и видео, отправленных вместе, он общий. Его сообщают
-- живая сессия и догрузка истории (Telethon `message.grouped_id`) и бизнес-режим (`media_group_id`,
-- если он число). В выгрузке Telegram Desktop такого поля нет: там альбом собирается по паузам.
--
-- rush_at — вложение или голосовое поднято в начало очереди разбора: по нему готовится ответ
-- (репетиция, «Подготовить ответ», черновик, автоответ) или идёт разбор входящих. Очереди разбора
-- фото и документов (media/) и расшифровки (voice/) берут такие строки первыми. Само включение
-- разбора и расшифровки этим не меняется: их по-прежнему включает только владелец.
ALTER TABLE messages
    ADD COLUMN grouped_id bigint,
    ADD COLUMN rush_at    timestamptz;

-- Карточка репетиции (Р-85) — на всю пачку: номера её сообщений (без текста) и честные строки о том,
-- чего ассистент не видел («Фото не успел разобрать», «Фото не смотрел: разбор выключен…») — готовыми
-- фразами сервиса, без слов переписки.
ALTER TABLE rehearsal_items
    ADD COLUMN pack_ids    bigint[] NOT NULL DEFAULT '{}',
    ADD COLUMN media_notes text[]   NOT NULL DEFAULT '{}';
