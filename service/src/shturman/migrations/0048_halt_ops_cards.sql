-- «Остановить всё» и сопровождение сервера (ОТ-51, решение Р-106).
--
-- Остановка выключает действия ассистента. Разрешения на сопровождение (`ops.consent`: обновление с откатом
-- базы, восстановление, откат, удаление копий, порог защиты, перезапуск без копии) и отчёт сопровождения
-- (`ops.report`) — не действия ассистента: их просит скрипт `ops/` на сервере (маршрут `/api/ops/consents` —
-- только токеном оператора, отчёт — командой в контейнере сервиса, у ассистента в Hermes пути к ним нет),
-- а решает только владелец нажатием в самом боте согласований. Раньше вторая линия в базе не давала завести
-- и эти карточки: при остановке сервис отвечал скрипту 500, и тот считал сервис зависшим.
-- Теперь при остановке, кроме «Продолжить» и входа по коду, заводятся и эти две карточки. Остальные
-- подтверждения — по-прежнему нет.
DROP TRIGGER pending_actions_halt ON pending_actions;
CREATE TRIGGER pending_actions_halt BEFORE INSERT ON pending_actions
    FOR EACH ROW WHEN (NEW.kind NOT IN ('halt.resume', 'setup.code_login', 'ops.consent', 'ops.report'))
    EXECUTE FUNCTION shturman_halt_guard();
