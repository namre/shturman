-- Индексы чтения архива.
--
-- История без указания чата и отправителя («что было вчера», «мои исходящие за неделю»)
-- упорядочена по времени и идентификатору. Без этого индекса такой запрос сортирует весь архив.
-- Создание индекса на большом архиве занимает время и на это время блокирует запись в messages:
-- миграции идут в транзакции, поэтому CONCURRENTLY здесь недоступен.
CREATE INDEX IF NOT EXISTS messages_time ON messages (sent_at, id);
