-- Вид страницы проекта (Р-112, разбор памяти пилота: проект-«свалка»).
--
-- kind — что это:
--   project      — объект, сделка, работа: как было до сих пор;
--   organization — компания, заказчик, подрядчик, контрагент;
--   unit         — подразделение: отдел, служба, филиал внутри организации.
-- Организация и подразделение ведутся той же страницей с теми же чатами, другими названиями,
-- договорённостями и фактами, но статус, срок, бюджет и цена работы к ним по ключу не пишутся:
-- значения работы — у проекта (processing/projects.py, WORK_SLOTS).
-- Всё, что заведено до 0.0.17, остаётся проектом: вид меняет владелец («Память» → «Проекты»).
ALTER TABLE projects
    ADD COLUMN kind text NOT NULL DEFAULT 'project' CHECK (kind IN ('project', 'organization', 'unit'));

-- Как назвала упоминание модель (null — не назвала: ответ без вида читается как раньше).
ALTER TABLE project_mentions
    ADD COLUMN kind text CHECK (kind IS NULL OR kind IN ('project', 'organization', 'unit'));
