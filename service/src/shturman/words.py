def counted(n: int, one: str, few: str, many: str) -> str:
    """«1 черновик», «3 черновика», «5 черновиков»."""
    n = int(n)
    if n % 10 == 1 and n % 100 != 11:
        word = one
    elif n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        word = few
    else:
        word = many
    return f"{n} {word}"
